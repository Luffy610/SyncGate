package in.syncgate.api.backup;

import in.syncgate.api.config.SyncgateProperties;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.regex.Pattern;
import org.springframework.stereotype.Component;

/**
 * Where finished backup files are kept. The default writes to a local folder
 * and doubles as the stand-in for Google Drive (ADR-0013): the Drive client
 * (google_sign_in + Drive v3, scope drive.file) is a second implementation of
 * this contract and is not built yet. Files are already encrypted when they
 * reach the store, so a store never sees plaintext.
 */
public interface BackupStore {

    String destinationName();

    void put(String fileName, byte[] bytes);

    byte[] get(String fileName);

    void delete(String fileName);

    @Component
    class LocalFolder implements BackupStore {
        private static final Pattern SAFE_NAME = Pattern.compile("^[A-Za-z0-9._-]{1,120}$");
        private final Path dir;

        public LocalFolder(SyncgateProperties props) {
            this.dir = Path.of(props.backup().dir()).toAbsolutePath().normalize();
        }

        @Override
        public String destinationName() {
            return "Local folder";
        }

        @Override
        public void put(String fileName, byte[] bytes) {
            try {
                Files.createDirectories(dir);
                Path target = resolve(fileName);
                // Write to a temp file and rename, so a crash never leaves half a backup.
                Path temp = Files.createTempFile(dir, "upload-", ".tmp");
                Files.write(temp, bytes);
                Files.move(temp, target, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
        }

        @Override
        public byte[] get(String fileName) {
            try {
                return Files.readAllBytes(resolve(fileName));
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
        }

        @Override
        public void delete(String fileName) {
            try {
                Files.deleteIfExists(resolve(fileName));
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
        }

        /** File names are generated by the server, but are checked anyway against path tricks. */
        private Path resolve(String fileName) {
            if (!SAFE_NAME.matcher(fileName).matches()) {
                throw new IllegalArgumentException("unsafe backup file name");
            }
            Path path = dir.resolve(fileName).normalize();
            if (!path.startsWith(dir)) {
                throw new IllegalArgumentException("unsafe backup file name");
            }
            return path;
        }
    }
}
